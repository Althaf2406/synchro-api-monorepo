# 3. MULTI-AGENT ORCHESTRATOR CLIENT (BASETEN + FIREWORKS AI + SIMULATION FALLBACK)
# =============================================================================

class SynchroMultiAgentOrchestrator:
    """
    Klien orkestrasi asinkron yang mengintegrasikan Muse Spark Open (Baseten)
    dan Muse Code (Fireworks AI) dengan JSON Schema Enforcement & Prompt Caching.
    """

    def __init__(self, simulate_self_healing_on_iter1: bool = False) -> None:
        self.baseten_key = os.environ.get("BASETEN_API_KEY", "mock-key")
        self.fireworks_key = os.environ.get("FIREWORKS_API_KEY", "mock-key")
        self.simulate_self_healing_on_iter1 = simulate_self_healing_on_iter1

        # Baseten High-Throughput Endpoint (2M TPM) untuk Muse Spark Open
        self.baseten_client = AsyncOpenAI(
            api_key=self.baseten_key,
            base_url=os.environ.get("BASETEN_BASE_URL", "https://bridge.baseten.co/v1/direct"),
        )
        # Fireworks AI Low-Latency Endpoint dengan Speculative Decoding untuk Muse Code
        self.fireworks_client = AsyncOpenAI(
            api_key=self.fireworks_key,
            base_url=os.environ.get("FIREWORKS_BASE_URL", "https://api.fireworks.ai/inference/v1"),
        )
        self.muse_spark_model = os.environ.get("MUSE_SPARK_MODEL_ID", "meta-llama/Muse-Spark-Open-70B")
        self.muse_code_model = os.environ.get("MUSE_CODE_MODEL_ID", "accounts/fireworks/models/muse-code-34b-instruct")

    @property
    def is_live_api_configured(self) -> bool:
        return (
            self.baseten_key not in {"", "mock-key"}
            and self.fireworks_key not in {"", "mock-key"}
            and os.environ.get("SYNCHRO_FORCE_SIMULATION", "0") != "1"
        )

    async def generate_migration_plan(
        self,
        target_repo: str,
        breaking_changes: List[Dict[str, Any]],
        repo_subgraph: Dict[str, Any],
    ) -> RepoMigrationPlan:
        """
        Memanggil Manager Agent (Muse Spark Open) untuk menyusun rencana migrasi lintas file
        berdasarkan output oasdiff dan sub-graf GraphRAG.
        """
        if not self.is_live_api_configured:
            return self._simulate_migration_plan(target_repo, repo_subgraph)

        user_payload = {
            "target_repo": target_repo,
            "oasdiff_breaking_changes": breaking_changes,
            "graphrag_blast_radius_subgraph": repo_subgraph,
        }

        response = await self.baseten_client.beta.chat.completions.parse(
            model=self.muse_spark_model,
            temperature=0.0,
            messages=[
                {"role": "system", "content": MANAGER_MUSE_SPARK_SYSTEM_PROMPT},
                {"role": "user", "content": json.dumps(user_payload, indent=2)},
            ],
            response_format=RepoMigrationPlan,
        )
        return response.choices[0].message.parsed

    async def synthesize_surgical_patches(
        self,
        target_repo: str,
        iteration: int,
        migration_plan: RepoMigrationPlan,
        repo_subgraph: Dict[str, Any],
        current_files: Dict[str, str],
        previous_diagnostic_feedback: Optional[str] = None,
        sandbox_stderr: Optional[str] = None,
    ) -> ExecutorPatchOutput:
        """
        Memanggil Surgical Executor Agent (Muse Code) pada Fireworks AI dengan dukungan
        Prompt Caching pada konteks sub-graf statis dan umpan balik iteratif dari Sandbox.
        """
        if not self.is_live_api_configured:
            return self._simulate_surgical_patches(target_repo, iteration)

        static_context = {
            "target_repo": target_repo,
            "migration_plan": migration_plan.model_dump(),
            "graphrag_ast_subgraph": repo_subgraph,
        }
        dynamic_iteration_context = {
            "iteration": iteration,
            "current_files": current_files,
            "previous_diagnostic_feedback": previous_diagnostic_feedback,
            "sandbox_stderr": sandbox_stderr,
        }

        response = await self.fireworks_client.beta.chat.completions.parse(
            model=self.muse_code_model,
            temperature=0.05,
            extra_body={
                "prompt_cache_max_len": 16384,  # Aktifkan Fireworks Prompt Caching untuk iterasi retry
                "speculative_decoding": True,
            },
            messages=[
                {"role": "system", "content": EXECUTOR_MUSE_CODE_SYSTEM_PROMPT},
                {
                    "role": "user",
                    "content": (
                        f"### STATIC GRAPHRAG & MIGRATION PLAN CONTEXT:\n{json.dumps(static_context, indent=2)}\n\n"
                        f"### DYNAMIC ITERATION & DIAGNOSTIC CONTEXT:\n{json.dumps(dynamic_iteration_context, indent=2)}"
                    ),
                },
            ],
            response_format=ExecutorPatchOutput,
        )
        return response.choices[0].message.parsed

    async def evaluate_sandbox_and_purity(
        self,
        target_repo: str,
        migration_plan: RepoMigrationPlan,
        original_files: Dict[str, str],
        patch_output: ExecutorPatchOutput,
        sandbox_telemetry: Dict[str, Any],
    ) -> CriticEvaluationOutput:
        """
        Memanggil Critic Agent (Muse Spark Open) untuk memverifikasi hasil eksekusi
        modal.Sandbox dan kemurnian semantik kode sebelum mengizinkan pembuatan PR.
        """
        if not self.is_live_api_configured:
            return self._simulate_critic_evaluation(target_repo, patch_output, sandbox_telemetry)

        audit_payload = {
            "target_repo": target_repo,
            "invariant_assertions": migration_plan.invariant_assertions,
            "original_files": original_files,
            "proposed_patches": patch_output.model_dump(),
            "sandbox_telemetry": sandbox_telemetry,
        }

        response = await self.baseten_client.beta.chat.completions.parse(
            model=self.muse_spark_model,
            temperature=0.0,
            messages=[
                {"role": "system", "content": CRITIC_MUSE_SPARK_SYSTEM_PROMPT},
                {"role": "user", "content": json.dumps(audit_payload, indent=2)},
            ],
            response_format=CriticEvaluationOutput,
        )
        return response.choices[0].message.parsed

