from pydantic import BaseModel, Field


# =============================================================================
# 1. PYDANTIC SCHEMAS UNTUK STRUCTURED OUTPUTS (JSON SCHEMA ENFORCEMENT)
# =============================================================================

class TransformationRule(BaseModel):
    node_id: str = Field(description="ID node GraphRAG yang harus dimodifikasi")
    file_path: str = Field(description="Path relatif file di dalam repositori downstream")
    action: Literal["UPDATE_DTO_SCHEMA", "REFACTOR_CALLSITE", "UPDATE_UNIT_TEST"]
    transformation_logic: str = Field(
        description="Instruksi presisi perubahan AST, pemetaan tipe baru, dan konversi nilai"
    )


class RepoMigrationPlan(BaseModel):
    target_repo: str
    semantic_transformation_rules: List[TransformationRule]
    file_execution_sequence: List[str] = Field(
        description="Urutan file yang harus dimodifikasi secara topologis (models -> client/service -> tests)"
    )
    invariant_assertions: List[str] = Field(
        description="Daftar invarian logika bisnis yang TIDAK BOLEH berubah selama refactoring"
    )


class FilePatchItem(BaseModel):
    file_path: str = Field(description="Path relatif file yang diperbarui")
    patched_content: str = Field(description="Kode sumber file Python utuh yang telah direfaktor")
    ast_nodes_modified: List[str] = Field(description="Daftar node AST yang telah ditransformasi")
    change_summary: str = Field(description="Penjelasan singkat perubahan pada file ini")


class ExecutorPatchOutput(BaseModel):
    target_repo: str
    iteration: int
    patches: List[FilePatchItem]


class CriticEvaluationOutput(BaseModel):
    approved: bool = Field(
        description="True HANYA JIKA sandbox exit_code == 0 DAN tidak ada semantic drift atau test cheating"
    )
    semantic_purity_score: float = Field(
        description="Skor kemurnian logika bisnis dari 0.0 hingga 1.0"
    )
    violated_invariants: List[str] = Field(
        description="Daftar invarian bisnis atau aturan kualitas kode yang dilanggar"
    )
    diagnostic_feedback_for_executor: str = Field(
        description="Instruksi perbaikan tingkat baris kode untuk Muse Code jika approved == False"
    )


